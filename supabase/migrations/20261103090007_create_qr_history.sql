/*
# Create qr_history table (single-tenant, no auth)

## Purpose
Stores a record of every QR code generated by users so they can browse
and re-download their previously created royal QR codes from the History tab.

## New Tables
- `qr_history`
  - `id` (uuid, primary key)
  - `content` (text, not null) — the encoded URL/text
  - `dark_color` (text) — foreground color hex
  - `light_color` (text) — background color hex
  - `size` (integer) — output resolution in pixels
  - `has_logo` (boolean, default false) — whether a crest was attached
  - `image_data` (text) — base64 data URL of the generated QR PNG
  - `filename` (text) — suggested download filename
  - `created_at` (timestamptz, default now())

## Security
- Enable RLS on `qr_history`.
- Grant CRUD to `anon` + `authenticated` so the no-auth frontend can
  read and write its history through the anon key.
- All policies use `USING (true)` / `WITH CHECK (true)` because this is
  an intentionally public/shared single-tenant dataset (no sign-in screen).
*/

CREATE TABLE IF NOT EXISTS qr_history (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  content text NOT NULL,
  dark_color text,
  light_color text,
  size integer,
  has_logo boolean NOT NULL DEFAULT false,
  image_data text,
  filename text,
  created_at timestamptz DEFAULT now()
);

ALTER TABLE qr_history ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON qr_history TO anon, authenticated;

DROP POLICY IF EXISTS "anon_select_qr_history" ON qr_history;
CREATE POLICY "anon_select_qr_history"
ON qr_history FOR SELECT
TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "anon_insert_qr_history" ON qr_history;
CREATE POLICY "anon_insert_qr_history"
ON qr_history FOR INSERT
TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "anon_update_qr_history" ON qr_history;
CREATE POLICY "anon_update_qr_history"
ON qr_history FOR UPDATE
TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "anon_delete_qr_history" ON qr_history;
CREATE POLICY "anon_delete_qr_history"
ON qr_history FOR DELETE
TO anon, authenticated USING (true);

CREATE INDEX IF NOT EXISTS idx_qr_history_created_at ON qr_history (created_at DESC);
